"""
Check method names of a REST API client package generated by hiveio-api-client-generator.

Fails when a class of the package has two public methods of the same name (a later definition silently replaces the
earlier one) or when the given URL paths are not served by distinct methods.

Usage: check_generated_rest_method_names.py <package_dir> <url_path> [<url_path> ...]
"""

from __future__ import annotations

import argparse
import ast
import sys
from collections import Counter
from importlib.metadata import version
from pathlib import Path

_GENERATOR_DISTRIBUTION = "hiveio-api-client-generator"


def _public_methods(class_def: ast.ClassDef) -> list[ast.FunctionDef | ast.AsyncFunctionDef]:
    return [
        node
        for node in class_def.body
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and not node.name.startswith("_")
    ]


def _endpoint_url_path(method: ast.FunctionDef | ast.AsyncFunctionDef) -> str | None:
    """URL path of an `@endpoint_rest.<http method>("<url path>")` decorator of the method, if it has one."""
    for decorator in method.decorator_list:
        if (
            isinstance(decorator, ast.Call)
            and isinstance(decorator.func, ast.Attribute)
            and isinstance(decorator.func.value, ast.Name)
            and decorator.func.value.id == "endpoint_rest"
            and decorator.args
            and isinstance(decorator.args[0], ast.Constant)
            and isinstance(decorator.args[0].value, str)
        ):
            return decorator.args[0].value
    return None


def _check(package_dir: Path, expected_url_paths: list[str]) -> list[str]:
    errors: list[str] = []
    methods_by_url_path: dict[str, list[str]] = {}
    for source in sorted(package_dir.rglob("*.py")):
        module = ast.parse(source.read_text(), filename=str(source))
        for class_def in (node for node in ast.walk(module) if isinstance(node, ast.ClassDef)):
            methods = _public_methods(class_def)
            duplicates = sorted(name for name, count in Counter(method.name for method in methods).items() if count > 1)
            errors.extend(
                f"{source}: class {class_def.name} defines method {name!r} more than once" for name in duplicates
            )
            for method in methods:
                url_path = _endpoint_url_path(method)
                if url_path is not None:
                    methods_by_url_path.setdefault(url_path, []).append(f"{class_def.name}.{method.name}")

    names_of_expected: dict[str, str] = {}
    for url_path in expected_url_paths:
        serving = methods_by_url_path.get(url_path, [])
        if len(serving) != 1:
            errors.append(f"expected one method for {url_path}, found {serving or 'none'}")
        else:
            names_of_expected[url_path] = serving[0]
    for name, count in Counter(names_of_expected.values()).items():
        if count > 1:
            shared_by = [url_path for url_path, serving_name in names_of_expected.items() if serving_name == name]
            errors.append(f"{name} serves several URL paths: {shared_by}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("package_dir", type=Path, help="directory of the generated package")
    parser.add_argument("url_paths", nargs="+", help="URL paths that must be served by distinct methods")
    args = parser.parse_args()

    print(f"{_GENERATOR_DISTRIBUTION} {version(_GENERATOR_DISTRIBUTION)}", flush=True)
    if not args.package_dir.is_dir():
        print(f"{args.package_dir} is not a directory", file=sys.stderr)
        return 1

    errors = _check(args.package_dir, args.url_paths)
    for error in errors:
        print(error, file=sys.stderr)
    if errors:
        return 1
    print(f"method names of {args.package_dir} are unique, {len(args.url_paths)} URL paths have distinct methods")
    return 0


if __name__ == "__main__":
    sys.exit(main())
